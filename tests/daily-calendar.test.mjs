import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { newDaily, stateAt, updateTask, visibleTasks } from '../daily-model.js';
import { syncCalendarTasks } from '../daily-calendar.js';
import { validateCalendar } from '../calendar-model.js';
import { createApp } from '../server.js';
const now = new Date('2026-10-11T02:00:00Z');
const event = () => ({ id: randomUUID(), title: 'Meeting', start: '2026-10-10T16:30:00.000Z', timeZone: 'Asia/Shanghai' });
test('Calendar maps local starting date, time, optional fields and categories, idempotently', () => {
  const doc = newDaily(randomUUID()), e = event(), calendar = { events: [e] };
  assert.equal(syncCalendarTasks(doc, calendar, now), true);
  assert.equal(doc.tasks[0].originDate, '2026-10-11');
  assert.equal(doc.tasks[0].versions[0].time, '00:30');
  assert.equal(doc.tasks[0].versions[0].categoryId, 'category-5');
  assert.equal(syncCalendarTasks(doc, calendar, now), false);
  e.categoryId = 'category-1'; e.location = 'Room A'; e.durationMinutes = 30;
  syncCalendarTasks(doc, calendar, now);
  assert.equal(doc.tasks.length, 1); assert.equal(doc.tasks[0].id, e.id);
  assert.equal(doc.tasks[0].versions[0].details, 'Room A\nDuration: 30 minutes');
  assert.equal(doc.tasks[0].versions[0].categoryId, 'category-1');
  e.categoryId = 'missing'; syncCalendarTasks(doc, calendar, now);
  assert.equal(doc.tasks[0].versions[0].categoryId, 'category-5');
});
test('edits retain dated completion and personal fields; deletion cancels once, preserving history', () => {
  const doc = newDaily(randomUUID()), e = event(), calendar = { events: [e] };
  e.start = '2026-10-09T02:00:00.000Z'; syncCalendarTasks(doc, calendar, now);
  const task = doc.tasks[0]; updateTask(task, '2026-10-10', { status: 'completed', details: 'Personal note', subtasks: [{ id: randomUUID(), text: 'Preparation', done: true }] });
  e.title = 'Updated meeting'; syncCalendarTasks(doc, calendar, now);
  assert.equal(stateAt(task, '2026-10-09').text, 'Meeting');
  assert.equal(stateAt(task, '2026-10-11').text, 'Updated meeting');
  assert.equal(stateAt(task, '2026-10-11').status, 'completed');
  assert.equal(stateAt(task, '2026-10-11').details, 'Personal note');
  assert.equal(stateAt(task, '2026-10-11').subtasks.length, 1);
  assert.equal(syncCalendarTasks(doc, { events: [] }, now), true);
  assert.equal(stateAt(task, '2026-10-11').status, 'cancelled');
  assert.equal(stateAt(task, '2026-10-10').status, 'completed');
  assert.equal(syncCalendarTasks(doc, { events: [] }, now), false);
  assert.equal(visibleTasks(doc, '2026-10-12').length, 0);
});
test('future events wait, reschedule across year boundaries and move earlier without duplicate tasks', () => {
  const doc = newDaily(randomUUID()), e = event(); e.start = '2026-12-31T16:30:00.000Z';
  syncCalendarTasks(doc, { events: [e] }, now);
  assert.equal(visibleTasks(doc, '2026-12-31').length, 0);
  assert.equal(visibleTasks(doc, '2027-01-01').length, 1);
  e.start = '2026-10-12T01:00:00.000Z'; syncCalendarTasks(doc, { events: [e] }, now);
  assert.equal(doc.tasks.length, 1); assert.equal(doc.tasks[0].originDate, '2026-10-12');
  assert.equal(visibleTasks(doc, '2026-10-11').length, 0);
  assert.equal(visibleTasks(doc, '2026-10-12')[0].state.time, '09:00');
  e.start = '2027-01-02T01:00:00.000Z'; syncCalendarTasks(doc, { events: [e] }, now);
  assert.equal(visibleTasks(doc, '2027-01-01').length, 0);
  assert.equal(visibleTasks(doc, '2027-01-02')[0].state.time, '09:00');
});
test('Calendar rejects malformed optional category and timezone', () => {
  const doc = { schemaVersion: 1, id: randomUUID(), events: [event()] };
  doc.events[0].categoryId = 1; assert.throws(() => validateCalendar(doc), { status: 400 });
  delete doc.events[0].categoryId; doc.events[0].timeZone = 'Invalid/Zone'; assert.throws(() => validateCalendar(doc), { status: 400 });
});
test('saved Calendar reconciles through Daily/search, persists across restart, backs up and detects stale drafts', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'daily-calendar-'));
  await fs.mkdir(path.join(root, 'collections')); await fs.writeFile(path.join(root, 'collections/Notebook.md'), '# Notebook');
  const app = await createApp(root); t.after(async () => { await app.terminals.close(); await app.kernels.close(); await fs.rm(root, { recursive: true, force: true }); });
  const old = await app.daily.read(); const calendar = await app.calendar.read(); const e = event(); calendar.document.events.push(e); await app.calendar.save(calendar);
  const saved = await app.daily.read(); assert.equal(saved.document.tasks[0].id, e.id);
  assert.notEqual(saved.revision, old.revision); assert.deepEqual(await app.daily.read(), saved);
  assert.equal((await app.daily.search('Meeting')).length, 1);
  assert.equal((await app.daily.export('json')).document.tasks[0].id, e.id);
  assert.equal((await fs.readdir(path.join(root, '.notebook/daily/versions'))).length, 1);
  await assert.rejects(app.daily.save(old), { status: 409 });
  const restarted = await createApp(root); t.after(async () => { await restarted.terminals.close(); await restarted.kernels.close(); });
  assert.equal((await restarted.daily.read()).revision, saved.revision);
  const edited = await app.calendar.read(); edited.document.events[0].title = 'Changed event'; await app.calendar.save(edited);
  assert.equal((await app.daily.search('Changed event'))[0].taskId, e.id);
  const removed = await app.calendar.read(); removed.document.events = []; await app.calendar.save(removed);
  assert.equal((await app.daily.read()).document.tasks[0].versions.at(-1).status, 'cancelled');
});

test('explicit end time syncs to Daily in the event zone and end edits preserve personal notes', () => {
  const doc = newDaily(randomUUID()), e = event(); e.end = '2026-10-11T02:00:00.000Z';
  syncCalendarTasks(doc, { events: [e] }, now);
  const task = doc.tasks[0]; assert.equal(task.versions[0].details, 'Ends: 2026-10-11 10:00');
  e.end = '2026-10-11T03:00:00.000Z'; assert.equal(syncCalendarTasks(doc, { events: [e] }, now), true);
  assert.equal(task.versions[0].details, 'Ends: 2026-10-11 11:00');
  assert.equal(syncCalendarTasks(doc, { events: [e] }, now), false);
  updateTask(task, '2026-10-11', { details: 'Personal note' });
  delete e.end; syncCalendarTasks(doc, { events: [e] }, now);
  assert.equal(task.versions[0].details, 'Personal note'); assert.equal(doc.tasks.length, 1);
});
